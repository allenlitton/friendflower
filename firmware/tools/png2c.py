"""PNG (8-bit RGBA, as Chrome saves it) -> LVGL 9 ARGB8888 image in C. Standard library only."""
import struct, sys, zlib

def read_png(path):
    data = open(path, "rb").read()
    assert data[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    pos, idat, w = 8, b"", 0
    while pos < len(data):
        n, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        if kind == b"IHDR":
            w, h, depth, ctype, _, _, interlace = struct.unpack(">IIBBBBB", body)
            assert depth == 8 and ctype == 6 and not interlace, "need 8-bit RGBA, not interlaced"
        elif kind == b"IDAT":
            idat += body
        pos += 12 + n
    raw, stride, out, prev = zlib.decompress(idat), w * 4, bytearray(), bytearray(w * 4)
    for y in range(h):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for x in range(stride):
            a = line[x - 4] if x >= 4 else 0
            b = prev[x]
            c = prev[x - 4] if x >= 4 else 0
            if f == 1: line[x] = (line[x] + a) & 255
            elif f == 2: line[x] = (line[x] + b) & 255
            elif f == 3: line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c; pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        out += line; prev = line
    return w, h, out

def main(png, name, out):
    w, h, px = read_png(png)
    bgra = bytearray()
    for i in range(0, len(px), 4):
        r, g, b, a = px[i:i + 4]
        bgra += bytes((b, g, r, a))  # LVGL ARGB8888 is stored B, G, R, A
    rows = ",\n".join("  " + ",".join(str(v) for v in bgra[i:i + 32]) for i in range(0, len(bgra), 32))
    open(out, "w").write(f"""// Generated by tools/png2c.py from {png.split('/')[-1]} -- do not edit.
#include "lvgl.h"

static const uint8_t {name}_map[] = {{
{rows}
}};

const lv_image_dsc_t {name} = {{
  .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888, .w = {w}, .h = {h}, .stride = {w * 4} }},
  .data_size = sizeof({name}_map),
  .data = {name}_map,
}};
""")

if __name__ == "__main__":
    main(*sys.argv[1:4])
